-- ============================================================
-- queries.sql — 3 аналитических запроса к таблице companies
-- ============================================================

-- ============================================================
-- Запрос 1: Топ-5 категорий по числу компаний
-- ============================================================
SELECT
    category                    AS "Категория",
    COUNT(*)                    AS "Число компаний"
FROM companies
GROUP BY category
ORDER BY COUNT(*) DESC
LIMIT 5;


-- ============================================================
-- Запрос 2: Средний рейтинг по городам
--           среди компаний с 10+ отзывами
-- ============================================================
SELECT
    city                                    AS "Город",
    ROUND(AVG(rating), 2)                   AS "Средний рейтинг",
    COUNT(*)                                AS "Компаний (10+ отзывов)"
FROM companies
WHERE reviews_count >= 10
  AND rating IS NOT NULL
GROUP BY city
ORDER BY AVG(rating) DESC;


-- ============================================================
-- Запрос 3: Доля компаний с сайтом по категориям
-- ============================================================
SELECT
    category                                                        AS "Категория",
    COUNT(*)                                                        AS "Всего компаний",
    COUNT(site)                                                     AS "С сайтом",
    ROUND(100.0 * COUNT(site) / COUNT(*), 1)                        AS "Доля с сайтом, %"
FROM companies
GROUP BY category
ORDER BY ROUND(100.0 * COUNT(site) / COUNT(*), 1) DESC;
